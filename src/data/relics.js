// Реликвии — красный (высший) тир снаряжения. Их нельзя выбить целиком: с
// босса ДЕСЯТОЙ локации падают части, и только собрав все пять, игрок кует на
// верстаке случайную реликвию.
//
// Зачем так. Обычный лут выпадает случайно и мгновенно, поэтому высший тир либо
// достаётся по удаче (и обесценивает всё остальное), либо не достаётся вовсе.
// Набор из пяти частей превращает высший тир в ЦЕЛЬ: прогресс виден, каждая
// часть — событие, и путь к реликвии считается в часах, а не в бросках кубика.

