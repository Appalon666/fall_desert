// Единый источник правды по подаче боя: размер волны, длина зоны, опыт за килл.
// Импортируется боем и симуляторами, чтобы формулы не расходились.
//
// Масштабирование врагов идёт по КИЛЛАМ (stage = totalKills, см. scaling.js) —
// это само-балансирует TTK. Здесь только СТРУКТУРА подачи: волны как батчи и
// зоны как вехи, гейтящиеся числом убийств + боссом-воротами в конце зоны.

import { BAL } from './balance.js'

// Сколько врагов в очередной волне (батч на экране). Медленно растёт по зонам,
// плюс небольшая надбавка за зачистку внутри зоны.
//
// ПОЧЕМУ НАДБАВКА ОГРАНИЧЕНА. Раньше было «+1 враг за каждые 20 убийств» без
// потолка: при тогдашней норме зоны в 340 киллов волна доходила до 23 врагов. Темп
// игры = размер волны / время убийства, и урон по площади (Картечь, пробитие,
// ульта) бьёт по всей волне сразу. То есть с ростом волны игра не усложнялась,
// а РАЗГОНЯЛАСЬ: поздний темп был впятеро выше раннего, зоны пролетали за две
// минуты. Теперь надбавка упирается в waveKillBonusMax, и темп держится ровно.
export function enemiesInWave(zoneIndex, killsInZone = 0) {
  const byZone = Math.min(BAL.waveCountMax, BAL.waveCountBase + Math.floor(zoneIndex / 3))
  const byKills = Math.min(BAL.waveKillBonusMax, Math.floor(killsInZone / BAL.waveKillStep))
  return byZone + byKills
}

// ---- Поток врагов: как часто и сколько выпускать ----
// Одна формула на бой (BattleScene.spawnTick/scheduleSpawn) и на симуляторы —
// иначе замеры баланса врут ровно в тот момент, когда поток правят.
//
// Раньше поток был «один враг раз в 1.5-2.5 с» и не зависел от локации: арена
// пустовала, а глубина ощущалась так же, как первая зона. Теперь пачками, чаще,
// и с локацией и то и другое растёт.

// Интервал между пачками, мс. С каждой локацией короче, но не ниже потолка
// скорости spawnGapFloor — иначе на глубине поток превращается в сплошную стену,
// в которой уже ничего не читается.
export function spawnGap(zoneIndex) {
  const z = Math.max(0, Math.floor(zoneIndex) || 0)
  const k = Math.pow(BAL.spawnGapZoneDecay, z)
  let min = Math.max(BAL.spawnGapFloor, Math.round(BAL.spawnGapMin * k))
  let max = Math.max(min, Math.round(BAL.spawnGapMax * k))
  // Вторая ступень глубины (с BAL.abyssZoneStart) ускоряет поток на 2% за
  // локацию — и уводит его НИЖЕ обычного пола, до своего abyssGapFloor.
  // Иначе ускорять нечего: к 34-й локации интервал уже лежит на 260 мс.
  const deep = Math.max(0, (z + 1) - BAL.abyssZoneStart)
  if (deep > 0) {
    const a = Math.pow(BAL.abyssSpawnRamp, deep)
    min = Math.max(BAL.abyssGapFloor, Math.round(min * a))
    max = Math.max(min, Math.round(max * a))
  }
  return { min, max }
}

// Сколько врагов максимум выпускается за одну пачку на этой локации.
// Первая локация — по одному (новичку надо разобраться), дальше растёт до
// BAL.spawnBatchMax. Сам размер пачки бой бросает случайно от base до этого.
export function spawnBatchMax(zoneIndex) {
  const z = Math.max(0, Math.floor(zoneIndex) || 0)
  return Math.min(BAL.spawnBatchMax, BAL.spawnBatchBase + Math.floor(z / BAL.spawnBatchZoneStep))
}

// Норма убийств в зоне — одна для всех зон и глубин (BAL.zoneKills). Раньше
// здесь была растущая норма, из-за чего поздняя локация тянулась вчетверо
// дольше ранней при том же ощущении боя. Теперь счётчик зачистки на экране
// всегда означает одно и то же, а сложность читается по тому, как долго живёт
// враг, и по ступенькам локаций (ZONE_STEPS в zones.js).
export function zoneKillsFor() {
  return BAL.zoneKills
}

// ФИЗИЧЕСКИЙ ПОТОЛОК ТЕМПА УБИЙСТВ НА ЭТОЙ ЛОКАЦИИ, убийств в секунду боя.
//
// Убить можно только того, кто уже вышел на арену, а выходят враги пачками не
// больше spawnBatchMax(zone) и не чаще spawnGap(zone).min. Отсюда и потолок.
// Он ЩЕДРЫЙ: размер пачки бросается случайно от spawnBatchBase, поэтому даже
// идеальный автокликер, убивающий каждого врага мгновенно, выдаёт примерно
// две трети от этого числа — замерено в игре. Плюс потолок не учитывает ворота
// зон: каждые zoneKills убийств поток встаёт на босса и на окно «локация
// взята».
//
// СЧИТАЕТСЯ ПО ЛОКАЦИИ, а не одним числом на всю игру: на первой локации поток
// даёт 2 убийства в секунду, а за 60-й, где вторая ступень его разгоняет, — в
// двадцать раз больше. Плоский потолок пришлось бы брать по самой быстрой
// локации, и на мелководье он перестал бы что-либо значить.
//
// Нужен таблице рекордов: см. GameState.leaderboardScore.
export function maxKillsPerSec(zoneIndex) {
  const g = spawnGap(zoneIndex)
  return spawnBatchMax(zoneIndex) / (g.min / 1000)
}

// Самый быстрый темп, возможный в игре ВООБЩЕ. Нужен только для миграции старых
// сейвов и для отчётов инструментов.
export const MAX_KILLS_PER_SEC = BAL.spawnBatchMax / (BAL.abyssGapFloor / 1000)

// Пора ли выпускать босса-ворот (набрали норму убийств в зоне).
export function bossDue(killsInZone) {
  return killsInZone >= zoneKillsFor()
}

// Опыт за убийство. НЕ привязан к награде в крышках: крышки растут по
// rewardGrowth экспоненциально, и опыт вместе с ними обгонял порог уровня
// (1.18^lvl) настолько, что за 20 минут набегало 118 уровней — уровень
// переставал быть событием, а очки характеристик обесценивались. Отдельная,
// почти плоская кривая держит уровень редким и весомым.
// Кэп как в scaling.js: на экстремальной глубине (~886 тысяч убийств за один
// забег) экспонента даёт Infinity, а Infinity опыта превращает hero.xp в NaN
// внутри addXp. Достижимо только марафоном без перерождений, но стоит одну
// строку.
export function xpFromKill(totalKills) {
  const xp = BAL.xpPerKill * Math.pow(BAL.xpKillGrowth, totalKills)
  return Math.min(Number.MAX_SAFE_INTEGER, Math.ceil(xp))
}
